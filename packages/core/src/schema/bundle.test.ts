/**
 * Contract test for `vitae.graph.bundle/1`.
 *
 * The fixture this reads is byte-identical to `fixtures/vitae-bundle.golden.json`
 * in the Aperture repo, where an equivalent test runs against the Pydantic
 * implementation. If the two ever drift, one of the two suites goes red.
 */
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { NODE_PROPS_SCHEMAS } from './node-props.js';
import { edgeEndpointsAllowed } from '../forms/edge-forms.js';
import {
  BUNDLE_FORMAT,
  BUNDLE_SCHEMA_VERSION,
  externalNodeId,
  graphBundleSchema,
  parseGraphBundle,
} from './bundle.js';

const GOLDEN = fileURLToPath(new URL('../../../../fixtures/vitae-bundle.golden.json', import.meta.url));
const golden = JSON.parse(readFileSync(GOLDEN, 'utf8')) as unknown;

const sha256 = (s: string) => createHash('sha256').update(s).digest('hex');

describe('vitae.graph.bundle/1', () => {
  it('parses the golden fixture', () => {
    const result = parseGraphBundle(golden);
    if (!result.ok) throw new Error(JSON.stringify(result.errors, null, 2));
    expect(result.value.format).toBe(BUNDLE_FORMAT);
    expect(result.value.schema_version).toBe(BUNDLE_SCHEMA_VERSION);
    expect(result.value.source.system).toBe('aperture');
    expect(result.value.nodes).toHaveLength(12);
    expect(result.value.edges).toHaveLength(13);
  });

  it('exercises every new node type, edge type and enum value', () => {
    const b = graphBundleSchema.parse(golden);
    const nodeTypes = new Set(b.nodes.map((n) => n.type));
    const edgeTypes = new Set(b.edges.map((e) => e.type));

    expect(nodeTypes).toContain('post');
    for (const t of ['REACTED_TO', 'MEMBER_OF', 'FOLLOWS'] as const) expect(edgeTypes).toContain(t);

    const props = (ref: string) => b.nodes.find((n) => n.ref === ref)!.props as Record<string, unknown>;
    expect(props('publication:patent-us-11-000-000').pub_type).toBe('patent');
    expect(props('skill:arabic').category).toBe('spoken_language');
    expect(props('post:7013').post_kind).toBe('comment');
    expect(b.nodes.every((n) => n.source === 'import_aperture')).toBe(true);
  });

  it('every node’s props validate against its type schema', () => {
    const b = graphBundleSchema.parse(golden);
    for (const node of b.nodes) {
      const parsed = NODE_PROPS_SCHEMAS[node.type].safeParse(node.props);
      expect(parsed.success, `${node.ref} (${node.type})`).toBe(true);
    }
  });

  it('every edge is legal under the endpoint matrix', () => {
    const b = graphBundleSchema.parse(golden);
    const typeByRef = new Map(b.nodes.map((n) => [n.ref, n.type]));
    for (const edge of b.edges) {
      const result = edgeEndpointsAllowed(edge.type, typeByRef.get(edge.src)!, typeByRef.get(edge.dst)!);
      expect(result.ok, `${edge.type}: ${edge.src} → ${edge.dst}`).toBe(true);
    }
  });

  it('normalizes identity keys to lowercase so ids cannot fork on casing', () => {
    const b = graphBundleSchema.parse({
      ...(golden as Record<string, unknown>),
      nodes: [
        {
          ref: 'x',
          type: 'person',
          title: 'X',
          identity_keys: ['LinkedIn:Person:Jane-SMITH'],
          props: {},
        },
      ],
      edges: [],
    });
    expect(b.nodes[0]?.identity_keys[0]).toBe('linkedin:person:jane-smith');
    expect(externalNodeId('LinkedIn:Person:Jane-SMITH', sha256)).toBe(
      externalNodeId('linkedin:person:jane-smith', sha256),
    );
  });

  it('rejects a malformed identity key', () => {
    const result = parseGraphBundle({
      ...(golden as Record<string, unknown>),
      nodes: [{ ref: 'x', type: 'person', title: 'X', identity_keys: ['not-a-key'], props: {} }],
      edges: [],
    });
    expect(result.ok).toBe(false);
  });

  it('rejects duplicate refs', () => {
    const dup = { ref: 'dup', type: 'person', title: 'A', props: {} };
    const result = parseGraphBundle({ ...(golden as Record<string, unknown>), nodes: [dup, { ...dup, title: 'B' }], edges: [] });
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.errors.some((e) => e.message.includes('duplicate ref'))).toBe(true);
  });

  it('rejects an edge pointing at a ref that is not in the bundle', () => {
    const result = parseGraphBundle({
      ...(golden as Record<string, unknown>),
      nodes: [{ ref: 'a', type: 'person', title: 'A', props: {} }],
      edges: [{ type: 'KNOWS', src: 'a', dst: 'ghost' }],
    });
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.errors.some((e) => e.path === 'edges.0.dst')).toBe(true);
  });

  /**
   * The golden fixture is hand-written and proves the two implementations agree
   * on the *format*. This one is machine-generated by Aperture's real projection
   * code, and proves the thing that actually matters: what the producer emits is
   * something this graph will accept, every type known, every edge legal.
   */
  describe('a bundle produced by Aperture', () => {
    const produced = JSON.parse(
      readFileSync(
        fileURLToPath(new URL('../../../../fixtures/aperture-produced.sample.json', import.meta.url)),
        'utf8',
      ),
    ) as unknown;

    it('parses, and every node validates against its type schema', () => {
      const result = parseGraphBundle(produced);
      if (!result.ok) throw new Error(JSON.stringify(result.errors, null, 2));
      for (const node of result.value.nodes) {
        const parsed = NODE_PROPS_SCHEMAS[node.type].safeParse(node.props);
        expect(parsed.success, `${node.ref} (${node.type})`).toBe(true);
      }
    });

    it('emits only relationships the endpoint matrix allows', () => {
      const b = graphBundleSchema.parse(produced);
      const typeByRef = new Map(b.nodes.map((n) => [n.ref, n.type]));
      for (const edge of b.edges) {
        const result = edgeEndpointsAllowed(edge.type, typeByRef.get(edge.src)!, typeByRef.get(edge.dst)!);
        expect(result.ok, `${edge.type}: ${typeByRef.get(edge.src)} → ${typeByRef.get(edge.dst)}`).toBe(true);
      }
    });

    it('explodes one profile into many linked records, each externally identified', () => {
      const b = graphBundleSchema.parse(produced);
      const nodeTypes = new Set(b.nodes.map((n) => n.type));
      // The point of the exercise: a scrape is not one blob, it is a subgraph.
      expect(nodeTypes.size).toBeGreaterThanOrEqual(12);
      expect(new Set(b.edges.map((e) => e.type)).size).toBeGreaterThanOrEqual(14);
      expect(b.nodes.every((n) => n.identity_keys.length > 0)).toBe(true);

      // Everything hangs off the scraped person, not off whoever imports it.
      const jane = b.nodes.find((n) => n.type === 'person' && n.title === 'Jane Smith')!;
      const fromJane = b.edges.filter((e) => e.src === jane.ref).map((e) => e.type);
      expect(new Set(fromJane)).toEqual(
        new Set(['HELD', 'ATTENDED', 'USES_SKILL', 'EARNED', 'AUTHORED', 'WORKED_ON', 'COMPLETED', 'MEMBER_OF', 'FOLLOWS', 'RECOMMENDS', 'REACTED_TO', 'RELATES_TO']),
      );
    });
  });

  it('rejects an unknown schema_version rather than parsing best-effort', () => {
    expect(parseGraphBundle({ ...(golden as Record<string, unknown>), schema_version: 2 }).ok).toBe(false);
    expect(parseGraphBundle({ ...(golden as Record<string, unknown>), format: 'something.else' }).ok).toBe(false);
  });
});
