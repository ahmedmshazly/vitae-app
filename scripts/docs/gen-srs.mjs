#!/usr/bin/env node
/**
 * Maintain the requirement register inside docs/specs/srs.md.
 *
 * The defect this repairs: roughly a hundred requirement identifiers are cited
 * across services, algorithms, routes, tests and continuous integration, and
 * the specification they cite defined none of them. A reader who followed
 * `SRS FR-RES-009` from a source comment arrived at a document with no
 * identifiers in it at all. The spine was severed at the root.
 *
 * Only the block between the markers is generated. The prose around it stays
 * hand-written, because judgement about what the product is for is not
 * something a generator can hold.
 *
 * Usage: node scripts/docs/gen-srs.mjs [--check]
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = process.env.VITAE_DOCS_ROOT
  ? process.env.VITAE_DOCS_ROOT
  : join(dirname(fileURLToPath(import.meta.url)), '../..');
const TARGET = 'docs/specs/srs.md';
const START = '<!-- generated:requirement-register start -->';
const END = '<!-- generated:requirement-register end -->';

const read = (rel) => JSON.parse(readFileSync(join(root, rel), 'utf8'));
const requirements = read('docs/registry/requirements.json');
const capabilities = read('docs/registry/capabilities.json');
const trace = existsSync(join(root, 'docs/generated/traceability.json'))
  ? read('docs/generated/traceability.json')
  : { requirements: {} };

const EVIDENCE_PROSE = {
  'implemented-and-tested': 'cited by source and by tests',
  'implemented-untested': 'cited by source',
  'tested-only': 'cited by tests only',
  'documents-only': 'cited by documents only',
  uncited: 'cited nowhere',
};

const lines = [];
const put = (line = '') => lines.push(line);

put(START);
put();
put('<!-- Generated by scripts/docs/gen-srs.mjs. Edit docs/registry/requirements.json, then run `pnpm docs:gen`. -->');
put();
put('## Requirement register');
put();
put('Every identifier below is cited somewhere in this repository. None of them was');
put('defined here before this register existed: the identifiers were in the code and');
put('the specification had none, so a reader following `SRS FR-RES-009` from a source');
put('comment arrived at a document that never mentioned it.');
put();
put('The statements are therefore **recovered, not transcribed**. No authored');
put('specification containing these identifiers survives in the repository, so each');
put('statement is reconstructed from the code, tests and roadmap rows that cite it,');
put('and every entry is marked for review. Identifiers are adopted exactly as written');
put('and are never renumbered, because renumbering would invalidate live citations');
put('across source and continuous integration.');
put();
put('Where a statement could not be recovered without inventing it, none is recorded.');
put('An empty statement is an honest gap; a plausible one would be indistinguishable');
put('from a fabricated product claim.');
put();
put('| Field | Meaning |');
put('| --- | --- |');
put('| Status | Whether the behavior is enforced by shipped code in this repository. |');
put('| Evidence | Where the identifier is cited, derived by `scripts/docs/gen-traceability.mjs`. |');
put('| Provenance | `reconstructed` if a statement was recoverable, `unrecoverable` if not. |');
put();
put('Exact citation locations are in `docs/generated/traceability.json`. They are not');
put('repeated here, because line numbers move for reasons that have nothing to do with');
put('what a requirement means.');
put();

const byCapability = new Map(capabilities.capabilities.map((c) => [c.id, []]));
for (const req of requirements.requirements) byCapability.get(req.capability)?.push(req);

for (const cap of capabilities.capabilities) {
  const rows = byCapability.get(cap.id) ?? [];
  if (!rows.length) continue;
  put(`### ${cap.title}`);
  put();
  put(`\`${cap.id}\` · ${cap.summary}`);
  if (cap.status !== 'implemented') put(`\n**Status: ${cap.status}.** ${cap.note ?? ''}`.trimEnd());
  put();
  for (const req of rows) {
    const evidence = EVIDENCE_PROSE[trace.requirements?.[req.id]?.evidence] ?? 'not yet derived';
    put(`#### ${req.id}: ${req.title ?? 'No statement recovered'}`);
    put();
    put(req.statement ?? '_No statement is recorded for this identifier._');
    put();
    put(`Status: ${req.implementation_status} · Evidence: ${evidence} · Provenance: ${req.definition_provenance}, ${req.review}`);
    put();
    if (req.reconstruction_note) {
      put(`> ${req.reconstruction_note}`);
      put();
    }
  }
}

put('### Identifiers this register could not model');
put();
put('These are recorded so the gaps stay discoverable. A gap that nobody wrote down');
put('is indistinguishable from a gap that does not exist.');
put();
put('#### Unallocated or uncited numbers');
put();
put('| Range | Observation |');
put('| --- | --- |');
for (const gap of requirements.numbering_gaps) {
  put(`| \`${gap.range}\` | ${gap.observation} |`);
}
put();
put('#### Alternative spellings');
put();
put(requirements.alias_note);
put();
put('| Written as | Read as |');
put('| --- | --- |');
for (const [alias, canonical] of Object.entries(requirements.id_aliases)) {
  put(`| \`${alias}\` | \`${canonical}\` |`);
}
put();
put('#### Families beyond `FR` and `NFR`');
put();
put('| Family | Title | Numbering |');
put('| --- | --- | --- |');
for (const [name, family] of Object.entries(requirements.families ?? {})) {
  put(`| \`${name}\` | ${family.title} | ${family.numbering} |`);
}
put();
for (const marker of requirements.unmodelled_markers ?? []) {
  put(`**\`${marker.marker}\`**: ${marker.observation}`);
  put();
  put(`Cited at ${marker.cited_at.map((c) => `\`${c}\``).join(', ')}.`);
  put();
}
put(END);

const block = lines.join('\n');
const targetPath = join(root, TARGET);
const current = readFileSync(targetPath, 'utf8');
const from = current.indexOf(START);
const to = current.indexOf(END);
if (from === -1 || to === -1) {
  console.error(`${TARGET} has no generated:requirement-register markers. Add them before running this generator.`);
  process.exit(1);
}
const next = `${current.slice(0, from)}${block}${current.slice(to + END.length)}`;

if (process.argv.includes('--check')) {
  if (next !== current) {
    console.error(`${TARGET} requirement register is stale. Run \`pnpm docs:gen\` and commit the result.`);
    process.exit(1);
  }
  console.log('srs register: up to date');
} else {
  if (next !== current) writeFileSync(targetPath, next);
  const counted = requirements.requirements.length;
  console.log(`srs register: ${counted} requirements across ${capabilities.capabilities.length} capabilities`);
}
