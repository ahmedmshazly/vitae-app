import { test, expect } from '@playwright/test';
import { signIn } from './helpers/auth';
import { expectNoA11yViolations } from './helpers/a11y';

test('keeping a draft preserves browser Back and Forward history', async ({ page }, testInfo) => {
  await signIn(page);
  await page.getByRole('navigation', { name: 'Primary', exact: true }).getByRole('link', { name: /^Network/ }).click();
  await expect(page).toHaveURL(/\/network$/);
  await page.getByRole('navigation', { name: 'Primary', exact: true }).getByRole('link', { name: /^Career/ }).click();
  await expect(page).toHaveURL(/\/career$/);
  await page.goBack();
  await expect(page).toHaveURL(/\/network$/);
  const before = await page.evaluate(() => ({ length: history.length, idx: history.state.idx }));
  await page.getByRole('button', { name: 'Quick capture', exact: true }).click();
  const input = page.getByLabel('Capture line');
  await input.fill('i A draft worth keeping');
  await expect(page.getByRole('button', { name: 'Capture', exact: true })).toBeEnabled();
  await page.evaluate(() => history.forward());
  const prompt = page.getByRole('dialog', { name: 'Discard changes?', exact: true });
  await expect(prompt).toBeVisible();
  await expect(page).toHaveURL(/\/network$/);
  await expect(prompt.getByRole('button', { name: 'Keep editing' })).toBeFocused();
  await expectNoA11yViolations(page, '.vt-modal');
  await page.screenshot({ path: testInfo.outputPath('unsaved-navigation.png'), animations: 'disabled' });
  await prompt.getByRole('button', { name: 'Keep editing' }).click();
  await expect(input).toHaveValue('i A draft worth keeping');
  expect(await page.evaluate(() => ({ length: history.length, idx: history.state.idx }))).toEqual(before);
  await page.evaluate(() => history.back());
  await expect(prompt).toBeVisible();
  await expect(page).toHaveURL(/\/network$/);
  await prompt.getByRole('button', { name: 'Keep editing' }).click();
  expect(await page.evaluate(() => ({ length: history.length, idx: history.state.idx }))).toEqual(before);
  await page.evaluate(() => history.forward());
  await expect(prompt).toBeVisible();
  await prompt.getByRole('button', { name: 'Discard', exact: true }).click();
  await expect(page).toHaveURL(/\/career$/);
  await expect(prompt).toBeHidden();
  await expect(page.getByRole('dialog', { name: 'Quick add', exact: true })).toBeHidden();
  await expect(page.getByRole('main')).toBeFocused();
  await page.goBack();
  await expect(page).toHaveURL(/\/network$/);
  await page.getByRole('button', { name: 'Quick capture', exact: true }).click();
  await input.fill('i Another unsaved draft');
  await page.evaluate(() => history.back());
  await expect(prompt).toBeVisible();
  await prompt.getByRole('button', { name: 'Discard', exact: true }).click();
  await expect(page).toHaveURL(/\/today$/);
  await expect(page.getByRole('dialog', { name: 'Quick add', exact: true })).toBeHidden();
});

test('browser navigation cannot discard a capture while its save is pending', async ({ page }) => {
  await signIn(page);
  await page.getByRole('navigation', { name: 'Primary', exact: true }).getByRole('link', { name: /^Network/ }).click();
  await expect(page).toHaveURL(/\/network$/);
  let release!: () => void;
  const held = new Promise<void>((resolve) => { release = resolve; });
  await page.route('**/api/v1/capture', async (route) => { await held; await route.continue(); });
  await page.getByRole('button', { name: 'Quick capture', exact: true }).click();
  await page.getByLabel('Capture line').fill(`i Pending capture ${Date.now()}`);
  await page.getByRole('button', { name: 'Capture', exact: true }).click();
  await expect(page.getByLabel('Capture line')).toHaveAttribute('aria-busy', 'true');
  await page.evaluate(() => history.back());
  const prompt = page.getByRole('dialog', { name: 'Saving changes…', exact: true });
  await expect(prompt).toBeVisible();
  await expect(prompt.getByRole('button', { name: 'Saving…' })).toBeDisabled();
  await expect(page).toHaveURL(/\/network$/);
  release();
  await expect(page.getByRole('dialog', { name: 'Quick add', exact: true })).toBeHidden();
  await expect(prompt).toBeHidden();
  await expect(page).toHaveURL(/\/network$/);
});
